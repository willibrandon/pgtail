using System.Text;

namespace Pgtail.Detection;

/// <summary>
/// Turns on the logging collector in <c>postgresql.auto.conf</c>, the file <c>ALTER SYSTEM</c> writes.
/// </summary>
/// <remarks>
/// The server reads <c>postgresql.auto.conf</c> after <c>postgresql.conf</c> and every file that it includes, so the
/// setting there takes effect even when one of those files turns the collector off. Only the server's command line comes
/// later. The settings are read again after the change, to make sure that nothing still turns the collector off. The
/// defaults of <c>log_directory</c> and <c>log_filename</c> give the files pgtail looks for, and the server makes the
/// directory itself.
/// </remarks>
public static class LoggingEnabler
{
    // The lines ALTER SYSTEM starts the file with.
    private const string AutoConfHeader = "# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\n";

    /// <summary>
    /// Turns on the logging collector for a data directory.
    /// </summary>
    /// <param name="dataDirectory">The data directory.</param>
    /// <returns>The outcome.</returns>
    public static ConfigUpdate Enable(string dataDirectory)
    {
        ArgumentNullException.ThrowIfNull(dataDirectory);
        ServerSettings settings = ServerSettings.Read(dataDirectory);
        if (settings.ConfigFile is null)
        {
            var checkedPaths = new List<string> { Path.Join(dataDirectory, "postgresql.conf") };
            if (PostgresConf.DebianConfFile(dataDirectory) is { } debian)
            {
                checkedPaths.Add(debian);
            }

            return new ConfigUpdate(false, $"postgresql.conf not found.\n\nChecked:\n  {string.Join("\n  ", checkedPaths)}", []);
        }

        if (settings["logging_collector"] is { } collector)
        {
            if (collector.IsOn)
            {
                return new ConfigUpdate(true, $"logging_collector is already on in {collector.Source}.", []);
            }

            if (collector.File is null)
            {
                return new ConfigUpdate(false, CommandLineOverride(collector), []);
            }
        }

        string autoConf = settings.AutoConfFile;
        try
        {
            Set(autoConf, "logging_collector", "on");
        }
        catch (UnauthorizedAccessException)
        {
            return new ConfigUpdate(false,
                $"Permission denied writing to {autoConf}\n\n{string.Join('\n', PermissionAdvice.AutoConfPermission(autoConf))}", []);
        }
        catch (IOException exception)
        {
            return new ConfigUpdate(false, $"Cannot write {autoConf}: {exception.Message}", []);
        }

        List<string> changes = [$"Set logging_collector = 'on' in {autoConf}"];
        ConfigSetting? after = ServerSettings.Read(dataDirectory)["logging_collector"];
        if (after is not { IsOn: true })
        {
            string reason = after is { File: null }
                ? CommandLineOverride(after)
                : $"pgtail cannot read {autoConf} back, so the change cannot be checked.";
            return new ConfigUpdate(false, reason, changes);
        }

        return new ConfigUpdate(true, $"logging_collector is on in {after.Source}.", changes);
    }

    private static string CommandLineOverride(ConfigSetting collector) =>
        $"{collector.Source} sets logging_collector = '{collector.Value}'. The server reads its command line after all "
        + "configuration files, so a file cannot turn the collector on. Remove the setting from the command that starts the server.";

    // Sets a value as ALTER SYSTEM writes it: each line of the setting is replaced where it is, or a line is added at the
    // end. A new file starts with the lines ALTER SYSTEM writes first.
    private static void Set(string path, string name, string value)
    {
        string content = File.Exists(path) && File.ReadAllText(path) is { Length: > 0 } existing ? existing : AutoConfHeader;
        var output = new StringBuilder();
        bool found = false;
        foreach (string line in content.Split('\n'))
        {
            if (ConfigFileParser.ParseLine(line) is (string setting, string _) && setting.Equals(name, StringComparison.OrdinalIgnoreCase))
            {
                if (!found)
                {
                    output.Append($"{name} = '{value}'\n");
                    found = true;
                }

                continue;
            }

            output.Append(line).Append('\n');
        }

        string text = output.ToString();
        text = text.EndsWith("\n\n", StringComparison.Ordinal) ? text[..^1] : text;
        if (!found)
        {
            text += $"{name} = '{value}'\n";
        }

        File.WriteAllText(path, text);
    }
}
