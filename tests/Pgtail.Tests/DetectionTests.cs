    /// <summary>
    /// A file that postgresql.conf includes after it sets the collector wins, as ankus.conf does for an ankus cluster.
    /// </summary>
    [TestMethod]
    public void IncludedFileReadLaterWins()
    {
        using var environment = new TestEnvironment();
        string data = DataDirectory(environment, """
            logging_collector = on
            include = 'ankus.conf'
            """);
        File.WriteAllText(Path.Join(data, "ankus.conf"), "port = 28818\nlogging_collector = off\n");

        ConfigSetting? collector = ServerSettings.Read(data)["logging_collector"];

        Assert.IsNotNull(collector);
        Assert.AreEqual("off", collector.Value);
        Assert.AreEqual(Path.Join(data, "ankus.conf"), collector.File);
        Assert.AreEqual(2, collector.Line);
        Assert.IsFalse(collector.IsOn);
        Assert.AreEqual(28818, PostgresConf.GetPort(ServerSettings.Read(data)));
    }

    /// <summary>
    /// Include lines read their files where they stand, in the order the server reads them.
    /// </summary>
    /// <remarks>
    /// A directory gives its .conf files in name order, a missing optional file is skipped, and a relative path starts
    /// from the directory of the file that names it.
    /// </remarks>
    [TestMethod]
    public void IncludesReadInPlaceAndInOrder()
    {
        using var environment = new TestEnvironment();
        string data = DataDirectory(environment, """
            log_directory = 'first'
            include_dir = 'conf.d'
            include_if_exists = 'missing.conf'
            log_filename = 'main.log'
            """);
        string confD = Path.Join(data, "conf.d");
        Directory.CreateDirectory(confD);
        Directory.CreateDirectory(Path.Join(data, "shared"));
        File.WriteAllText(Path.Join(confD, "20-b.conf"), "log_directory = 'b'\n");
        File.WriteAllText(Path.Join(confD, "10-a.conf"), "log_directory = 'a'\nlog_filename = 'a.log'\n"
            + "include '../shared/extra.conf'\n");
        File.WriteAllText(Path.Join(confD, ".30-hidden.conf"), "log_directory = 'hidden'\n");
        File.WriteAllText(Path.Join(confD, "40-backup.conf.bak"), "log_directory = 'backup'\n");
        File.WriteAllText(Path.Join(data, "shared", "extra.conf"), "log_destination = 'csvlog'\n");

        ServerSettings settings = ServerSettings.Read(data);

        Assert.AreEqual("b", settings["log_directory"]?.Value);
        Assert.AreEqual(Path.Join(confD, "20-b.conf"), settings["log_directory"]?.File);
        Assert.AreEqual("main.log", settings["log_filename"]?.Value);
        Assert.AreEqual(4, settings["log_filename"]?.Line);
        Assert.AreEqual("csvlog", settings["LOG_DESTINATION"]?.Value);
    }

    /// <summary>
    /// postgresql.auto.conf, which ALTER SYSTEM writes, comes after every included file.
    /// </summary>
    [TestMethod]
    public void AutoConfComesAfterIncludedFiles()
    {
        using var environment = new TestEnvironment();
        string data = DataDirectory(environment, "include = 'logging.conf'\n");
        File.WriteAllText(Path.Join(data, "logging.conf"), "logging_collector = on\n");
        File.WriteAllText(Path.Join(data, "postgresql.auto.conf"), "# Do not edit this file manually!\nlogging_collector = 'off'\n");

        ConfigSetting? collector = ServerSettings.Read(data)["logging_collector"];

        Assert.AreEqual(Path.Join(data, "postgresql.auto.conf"), collector?.File);
        Assert.AreEqual(2, collector?.Line);
        Assert.IsFalse(ServerSettings.Read(data).IsOn("logging_collector"));
    }

    /// <summary>
    /// The command line in postmaster.opts comes after every file, in each form the server takes.
    /// </summary>
    [TestMethod]
    public void CommandLineComesAfterEveryFile()
    {
        using var environment = new TestEnvironment();
        string data = DataDirectory(environment, "port = 5432\nlogging_collector = off\n");
        File.WriteAllText(Path.Join(data, "postgresql.auto.conf"), "logging_collector = 'off'\n");
        File.WriteAllText(Path.Join(data, "postmaster.opts"),
            $"C:/Program Files/PostgreSQL/18/bin/postgres.exe \"-D\" \"{data}\" \"-c\" \"logging_collector=on\" "
            + "\"--log-directory=cmdlogs\" \"-p\" \"5499\" \"-iF\"\n");

        ServerSettings settings = ServerSettings.Read(data);

        Assert.IsTrue(settings.IsOn("logging_collector"));
        Assert.IsNull(settings["logging_collector"]?.File);
        Assert.AreEqual(0, settings["logging_collector"]?.Line);
        Assert.Contains("postmaster.opts", settings["logging_collector"]?.Source ?? "");
        Assert.AreEqual("cmdlogs", settings["log_directory"]?.Value);
        Assert.AreEqual("*", settings["listen_addresses"]?.Value);
        Assert.AreEqual("false", settings["fsync"]?.Value);
        Assert.AreEqual(5499, PostgresConf.GetPort(settings));
    }

    /// <summary>
    /// A config_file on the command line, as a Debian or Ubuntu cluster has, is the file read.
    /// </summary>
    [TestMethod]
    public void ConfigFileOnCommandLineIsRead()
    {
        using var environment = new TestEnvironment();
        string data = DataDirectory(environment, "port = 5432\n");
        string etc = Path.Join(environment.Root, "etc", "postgresql.conf");
        Directory.CreateDirectory(Path.GetDirectoryName(etc)!);
        File.WriteAllText(etc, "port = 5440\n");
        File.WriteAllText(Path.Join(data, "postmaster.opts"), $"/usr/bin/postgres \"-D\" \"{data}\" \"-c\" \"config_file={etc}\"\n");

        ServerSettings settings = ServerSettings.Read(data);

        Assert.AreEqual(etc, settings.ConfigFile);
        Assert.AreEqual(5440, PostgresConf.GetPort(settings));
    }

    /// <summary>
    /// Lines are read as the server reads them: quotes, escapes, comments, an optional equals sign, and lines it refuses.
    /// </summary>
    [TestMethod]
    public void LinesReadAsServerReadsThem()
    {
        Assert.AreEqual(("a", "it's"), ConfigFileParser.ParseLine("a = 'it''s'"));
        Assert.AreEqual(("b", @"C:\pglogs"), ConfigFileParser.ParseLine(@"b = 'C:\\pglogs'"));
        Assert.AreEqual(("c", "tab\there"), ConfigFileParser.ParseLine(@"c = 'tab\there'  # a comment"));
        Assert.AreEqual(("d", "A"), ConfigFileParser.ParseLine(@"d = '\101'"));
        Assert.AreEqual(("port", "5432"), ConfigFileParser.ParseLine("\tport 5432\r"));
        Assert.AreEqual(("pg_stat_statements.max", "10000"), ConfigFileParser.ParseLine("pg_stat_statements.max = 10000"));
        Assert.IsNull(ConfigFileParser.ParseLine("#logging_collector = on"));
        Assert.IsNull(ConfigFileParser.ParseLine("logging_collector = \"on\""));
        Assert.IsNull(ConfigFileParser.ParseLine("log_directory = 'open"));
        Assert.IsNull(ConfigFileParser.ParseLine("port = 5432 5433"));
        Assert.IsNull(ConfigFileParser.ParseLine("port ="));
    }

    /// <summary>
    /// Booleans are read as PostgreSQL reads them.
    /// </summary>
    [TestMethod]
    public void BooleansReadAsServerReadsThem()
    {
        foreach (string value in new[] { "on", "ON", "true", "t", "Tr", "yes", "y", "1" })
        {
            Assert.IsTrue(new ConfigSetting("logging_collector", value, null, 0).IsOn, value);
        }

        foreach (string value in new[] { "off", "o", "of", "false", "f", "no", "0", "2", "" })
        {
            Assert.IsFalse(new ConfigSetting("logging_collector", value, null, 0).IsOn, value);
        }
    }

    /// <summary>
    /// Absolute paths follow is_absolute_path: on Windows a leading separator, or a drive letter with a separator.
    /// </summary>
    [TestMethod]
    public void AbsolutePathsFollowServerRule()
    {
        foreach (string path in new[] { @"C:\pglogs", "C:/pglogs", @"\pglogs", "/pglogs", @"\\server\share\logs" })
        {
            Assert.IsTrue(PostgresPath.IsAbsolute(path, windows: true), path);
        }

        foreach (string path in new[] { "C:pglogs", "pglogs", "log/pg", "" })
        {
            Assert.IsFalse(PostgresPath.IsAbsolute(path, windows: true), path);
        }

        Assert.IsTrue(PostgresPath.IsAbsolute("/var/log/postgresql", windows: false));
        Assert.IsFalse(PostgresPath.IsAbsolute(@"C:\pglogs", windows: false));
        Assert.IsFalse(PostgresPath.IsAbsolute(@"\pglogs", windows: false));
    }

    /// <summary>
    /// An absolute log_directory, such as C:\pglogs on Windows, is used as it is, not joined to the data directory.
    /// </summary>
    [TestMethod]
    public void AbsoluteLogDirectoryKeepsItsPlace()
    {
        using var environment = new TestEnvironment();
        string logs = Path.Join(environment.Root, "pglogs");
        Directory.CreateDirectory(logs);
        string log = Path.Join(logs, "postgresql-2026-10-23.log");
        File.WriteAllText(log, "");
        string escaped = logs.Replace(@"\", @"\\", StringComparison.Ordinal);
        string data = DataDirectory(environment, $"logging_collector = on\nlog_directory = '{escaped}'\n");

        (string? path, string? directory, bool enabled) = PostgresConf.GetLogInfo(ServerSettings.Read(data), ServerLauncher.For(data));

        Assert.AreEqual(log, path);
        Assert.AreEqual(logs, directory);
        Assert.IsTrue(enabled);
    }

    /// <summary>
    /// current_logfiles gives an absolute file as it is and a relative one from the data directory.
    /// </summary>
    [TestMethod]
    public void CurrentLogfilesResolvesLikeServer()
