    /// <summary>
    /// An ankus cluster logs to the file that ankus records in .ankus-log.
    /// </summary>
    /// <remarks>
    /// postgresql.conf turns the collector on, and ankus.conf, which it includes later, turns it off.
    /// </remarks>
    [TestMethod]
    public void AnkusClusterLogsToRecordedFile()
    {
        using var environment = new TestEnvironment();
        string home = Path.Join(environment.Root, "ankus");
        string data = DataDirectories.CreateAnkusCluster(home, "pg18");
        string recorded = Path.Join(home, "clusters", "pg18.recorded.log");
        File.WriteAllText(recorded, "");
        File.WriteAllText(Path.Join(data, AnkusLauncher.LogPathFileName), recorded + "\n");

        ServerLauncher launcher = ServerLauncher.For(data);
        (string? path, string? directory, bool enabled) = PostgresConf.GetLogInfo(ServerSettings.Read(data), launcher);

        Assert.IsInstanceOfType<AnkusLauncher>(launcher);
        Assert.IsTrue(launcher.ManagesLogging);
        Assert.AreEqual(recorded, path);
        Assert.IsNull(directory);
        Assert.IsTrue(enabled);
        string option = home.Contains(' ', StringComparison.Ordinal) ? $"--home \"{home}\"" : $"--home {home}";
        string[] restart = [$"ankus stop --pg 18 {option}", $"ankus start --pg 18 {option}"];
        string[] start = [$"ankus start --pg 18 {option}"];
        Assert.AreSequenceEqual(restart, launcher.RestartCommands(running: true));
        Assert.AreSequenceEqual(start, launcher.RestartCommands(running: false));
    }

