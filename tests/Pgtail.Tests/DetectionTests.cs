    /// <summary>
    /// enable-logging changes nothing and fails when the server's command line turns the collector off.
    /// </summary>
    /// <remarks>
    /// The server reads its command line after every file, so no file can turn the collector on.
    /// </remarks>
    [TestMethod]
    public void EnableRefusesCommandLineOverride()
    {
        using var environment = new TestEnvironment();
        string data = DataDirectory(environment, "port = 5432\n");
        File.WriteAllText(Path.Join(data, "postmaster.opts"), $"/usr/bin/postgres \"-D\" \"{data}\" \"-c\" \"logging_collector=off\"\n");

