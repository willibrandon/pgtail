    /// <summary>
    /// Detection finds stopped ankus clusters in ANKUS_HOME and pgrx clusters in PGRX_HOME.
    /// </summary>
    [TestMethod]
    public void DetectionFindsAnkusAndPgrxHomes()
    {
        using var environment = new TestEnvironment();
        string ankusData = DataDirectories.CreateAnkusCluster(Path.Join(environment.Root, "ankus"), "pg18");
        string pgrxData = DataDirectories.CreatePgrxCluster(Path.Join(environment.Root, "pgrx"), "16");
        File.WriteAllText(Path.Join(environment.Root, "pgrx", "16.log"), "");
        environment.Set("ANKUS_HOME", Path.Join(environment.Root, "ankus"));
        environment.Set("PGRX_HOME", Path.Join(environment.Root, "pgrx"));

        IReadOnlyList<PostgresInstance> instances = new InstanceDetector(environment.Get, environment.Home, ProcessTable.List).DetectAll();

        PostgresInstance ankus = instances.Single(instance => Path.GetFullPath(instance.DataDirectory) == ankusData);
        PostgresInstance pgrx = instances.Single(instance => Path.GetFullPath(instance.DataDirectory) == pgrxData);
        Assert.AreEqual(DetectionSource.Ankus, ankus.Source);
        Assert.AreEqual("ankus", ankus.Source.ToName());
        Assert.IsInstanceOfType<AnkusLauncher>(ankus.Launcher);
        Assert.IsFalse(ankus.LoggingEnabled);
        Assert.AreEqual(DetectionSource.Pgrx, pgrx.Source);
        Assert.IsTrue(pgrx.LoggingEnabled);
        Assert.AreEqual(Path.Join(environment.Root, "pgrx", "16.log"), pgrx.LogPath);
    }

    /// <summary>
    /// enable-logging sets the collector in postgresql.auto.conf and leaves postgresql.conf as it was.
    /// </summary>
    /// <remarks>
    /// postgresql.auto.conf comes after the included file that turns the collector off.
    /// </remarks>
    [TestMethod]
    public void EnableSetsCollectorInAutoConf()
    {
        using var environment = new TestEnvironment();
        string data = DataDirectory(environment, "logging_collector = off\ninclude_dir = 'conf.d'\n");
        Directory.CreateDirectory(Path.Join(data, "conf.d"));
        File.WriteAllText(Path.Join(data, "conf.d", "logging.conf"), "logging_collector = off\n");
        string conf = File.ReadAllText(Path.Join(data, "postgresql.conf"));
        string autoConf = Path.Join(data, "postgresql.auto.conf");

        ConfigUpdate update = LoggingEnabler.Enable(data);

        Assert.IsTrue(update.Success, update.Message);
        string[] changes = [$"Set logging_collector = 'on' in {autoConf}"];
        Assert.AreSequenceEqual(changes, update.Changes);
        Assert.AreEqual(conf, File.ReadAllText(Path.Join(data, "postgresql.conf")));
        Assert.AreEqual(
            "# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\nlogging_collector = 'on'\n",
            File.ReadAllText(autoConf));
        Assert.AreEqual(autoConf, ServerSettings.Read(data)["logging_collector"]?.File);

        ConfigUpdate again = LoggingEnabler.Enable(data);

        Assert.IsTrue(again.Success);
        Assert.IsEmpty(again.Changes);
        Assert.AreEqual($"logging_collector is already on in {autoConf} line 3.", again.Message);
    }

