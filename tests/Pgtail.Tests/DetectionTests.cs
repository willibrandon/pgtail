        Assert.IsFalse(update.Success);
        Assert.Contains("postmaster.opts", update.Message);
        Assert.IsFalse(File.Exists(Path.Join(data, "postgresql.auto.conf")));
    }

    /// <summary>
    /// On Linux, with the collector off, the log of a running server is the file that its standard error goes to.
    /// </summary>
    /// <remarks>
    /// A server whose output goes nowhere has no log, whatever file its launcher would use.
    /// </remarks>
    [TestMethod]
    [OSCondition(OperatingSystems.Linux)]
    [SupportedOSPlatform("linux")]
    public void RunningServerOutputIsLog()
    {
        using var environment = new TestEnvironment();
        string home = Path.Join(environment.Root, "ankus");
        string data = DataDirectories.CreateAnkusCluster(home, "pg18");
        File.WriteAllText(Path.Join(home, "clusters", "pg18.log"), "");
        string output = Path.Join(environment.Root, "server.log");
        File.WriteAllText(output, "");

        using (Process server = StartServer(environment, data, output))
        {
            try
            {
                (string? path, string? _, bool enabled) = PostgresConf.GetLogInfo(ServerSettings.Read(data), ServerLauncher.For(data));
                Assert.AreEqual(output, path);
                Assert.IsTrue(enabled);
            }
            finally
            {
                server.Kill();
            }
        }

        using (Process server = StartServer(environment, data, "/dev/null"))
        {
            try
            {
                (string? path, string? _, bool enabled) = PostgresConf.GetLogInfo(ServerSettings.Read(data), ServerLauncher.For(data));
                Assert.IsNull(path);
                Assert.IsFalse(enabled);
            }
            finally
            {
                server.Kill();
            }
        }
    }

    // A data directory with PG_VERSION and a postgresql.conf of the given text.
    private static string DataDirectory(TestEnvironment environment, string conf)
    {
        string data = Path.Join(environment.Root, "pgdata");
        Directory.CreateDirectory(data);
        File.WriteAllText(Path.Join(data, "PG_VERSION"), "18\n");
        File.WriteAllText(Path.Join(data, "postgresql.conf"), conf);
        return data;
    }

    // A process named postgres with its standard error sent to a file, and the data directory's postmaster.pid naming it.
    [SupportedOSPlatform("linux")]
    private static Process StartServer(TestEnvironment environment, string data, string stderr)
    {
        string program = Path.Join(environment.Root, "bin", "postgres");
        if (!File.Exists(program))
        {
            Directory.CreateDirectory(Path.GetDirectoryName(program)!);
            File.Copy("/usr/bin/sleep", program);
            File.SetUnixFileMode(program, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute);
        }

        var info = new ProcessStartInfo("/bin/sh") { UseShellExecute = false };
        foreach (string argument in new[] { "-c", "exec \"$0\" 60 2>>\"$1\"", program, stderr })
        {
            info.ArgumentList.Add(argument);
        }

        Process server = Process.Start(info)!;
        SpinWait.SpinUntil(() => ProcessTable.NameOf(server.Id) == "postgres", TimeSpan.FromSeconds(10));
        File.WriteAllText(Path.Join(data, "postmaster.pid"), $"{server.Id}\n{data}\n0\n28818\n");
        return server;
    }
